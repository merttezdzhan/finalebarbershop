let currentLang = 'tr';

function changeLanguage(lang) {
    currentLang = lang;
    const dict = translations[lang];
    
    // Update text content
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (dict[key]) {
            element.textContent = dict[key];
        }
    });

    // Update document title
    document.title = dict['title'];

    // Update placeholders
    document.querySelectorAll('[data-placeholder-i18n]').forEach(element => {
        const key = element.getAttribute('data-placeholder-i18n');
        if (dict[key]) {
            element.setAttribute('placeholder', dict[key]);
        }
    });

    // Re-render time slots if a date is selected to update slot languages
    const dateInput = document.getElementById('date');
    if (dateInput && dateInput.value) {
        renderTimeSlots(dateInput.value);
    }
}

// --- End i18n ---

// Smooth scroll for nav links
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if(target) {
            target.scrollIntoView({
                behavior: 'smooth'
            });
        }
    });
});

// Select service from cards
function selectService(serviceNameTR) {
    const serviceSelect = document.getElementById('service');
    if (serviceSelect) {
        serviceSelect.value = serviceNameTR;
        document.getElementById('booking').scrollIntoView({ behavior: 'smooth' });
    }
}

// --- Calendar Logic ---
const workingHours = ["08:00", "09:00", "10:00", "11:00", "12:00", "13:00", "14:00", "15:00", "16:00", "17:00", "18:00"];
const dateInput = document.getElementById('date');
const timeSlotsContainer = document.getElementById('time-slots');
const selectedTimeInput = document.getElementById('selectedTime');

if (dateInput) {
    dateInput.addEventListener('change', (e) => {
        renderTimeSlots(e.target.value);
    });
}

function renderTimeSlots(date) {
    if (!date) return;
    
    selectedTimeInput.value = ''; // Reset selection
    timeSlotsContainer.innerHTML = '';
    
    // Get booked appointments for this date
    const appointments = JSON.parse(localStorage.getItem('barberAppointments')) || [];
    const bookedTimes = appointments
        .filter(app => app.date === date)
        .map(app => app.time);
    
    const dict = translations[currentLang];

    workingHours.forEach(time => {
        const isBooked = bookedTimes.includes(time);
        
        const slot = document.createElement('div');
        slot.className = `time-slot ${isBooked ? 'booked' : 'available'}`;
        slot.innerHTML = `
            ${time}
            <span>${isBooked ? dict.statusBooked : dict.statusAvailable}</span>
        `;
        
        if (!isBooked) {
            slot.addEventListener('click', () => {
                // Remove selected class from all
                document.querySelectorAll('.time-slot').forEach(el => el.classList.remove('selected'));
                // Add to current
                slot.classList.add('selected');
                selectedTimeInput.value = time;
            });
        }
        
        timeSlotsContainer.appendChild(slot);
    });
}
// --- End Calendar Logic ---

// Handle form submission
const bookingForm = document.getElementById('booking-form');

if (bookingForm) {
    bookingForm.addEventListener('submit', function(e) {
        e.preventDefault();
        
        // Get values
        const service = document.getElementById('service').value;
        const date = document.getElementById('date').value;
        const time = document.getElementById('selectedTime').value;
        const name = document.getElementById('name').value;
        const phone = document.getElementById('phone').value;
        
        if (!time) {
            alert(translations[currentLang].pleaseSelectTime);
            return;
        }

        // Create appointment object
        const appointment = {
            id: Date.now(),
            service,
            date,
            time,
            name,
            phone,
            status: 'Bekliyor',
            createdAt: new Date().toISOString()
        };
        
        // Save to LocalStorage
        let appointments = JSON.parse(localStorage.getItem('barberAppointments')) || [];
        appointments.push(appointment);
        localStorage.setItem('barberAppointments', JSON.stringify(appointments));
        
        // Show localized success message
        let successMsg = translations[currentLang].alertSuccess
            .replace('{name}', name)
            .replace('{date}', date)
            .replace('{time}', time)
            .replace('{service}', service);
            
        alert(successMsg);
        
        // Reset form and slots
        bookingForm.reset();
        selectedTimeInput.value = '';
        timeSlotsContainer.innerHTML = `<p class="time-placeholder" data-i18n="timePlaceholder">${translations[currentLang].timePlaceholder}</p>`;
    });
}
